let cars = ["bmw", "audi", "mercedes", "dodge"];

// push method add element in the last of array 
cars.push("ford");
console.log(cars);

// pop method delete the end element of the array  
cars.pop();
console.log(cars);

// unshift method add element in the start of array
cars.unshift("toyota");
console.log(cars);

// shift method delete the first element of the array
cars.shift("toyota");
console.log(cars);